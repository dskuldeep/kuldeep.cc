/**
 * Generates scripts/seed.sql from the legacy content/ markdown files plus
 * initial pages/projects rows. D1 can't be written from Node directly, so:
 *
 *   npm run seed
 *   npx wrangler d1 execute kuldeep-cc --local --file scripts/seed.sql
 *   npx wrangler d1 execute kuldeep-cc --remote --file scripts/seed.sql
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "scripts", "seed.sql");

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;

interface SeedPost {
  slug: string;
  title: string;
  excerpt: string;
  content: string;
  tags: string[];
  publishedAt: string;
}

function readDir(dir: string, extraTags: string[] = []): SeedPost[] {
  const full = path.join(ROOT, "content", dir);
  if (!fs.existsSync(full)) return [];
  return fs
    .readdirSync(full)
    .filter((f) => f.endsWith(".md"))
    .map((file) => {
      const { data, content } = matter(fs.readFileSync(path.join(full, file), "utf8"));
      const tags: string[] = [...(data.tags ?? []), ...extraTags];
      return {
        slug: file.replace(/\.md$/, ""),
        title: data.title ?? file,
        excerpt: data.excerpt || data.description || "",
        content: content.trim(),
        tags,
        publishedAt: `${data.date}T09:00:00Z`,
      };
    });
}

