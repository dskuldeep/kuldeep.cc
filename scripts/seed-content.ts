const lines: string[] = ["-- Generated by scripts/seed-content.ts. Do not edit by hand."];

for (const p of posts) {
  lines.push(
    `INSERT OR REPLACE INTO posts (slug, title, excerpt, content_md, tags, status, published_at) VALUES (` +
      [q(p.slug), q(p.title), q(p.excerpt), q(p.content), q(JSON.stringify(p.tags)), "'published'", q(p.publishedAt)].join(", ") +
      `);`,
  );
}

for (const p of pages) {
  lines.push(
    `INSERT OR REPLACE INTO pages (slug, title, content_md) VALUES (${q(p.slug)}, ${q(p.title)}, ${q(p.content)});`,
  );
}

lines.push(`DELETE FROM projects;`);
for (const p of projects) {
  lines.push(
    `INSERT INTO projects (title, url, description, year, sort_order) VALUES (` +
      [q(p.title), q(p.url), q(p.description), String(p.year), String(p.sort)].join(", ") +
      `);`,
  );
}

fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT}: ${posts.length} posts, ${pages.length} pages, ${projects.length} projects`);
